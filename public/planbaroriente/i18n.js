  function getParentLang() {
    try {
      if (window.parent && window.parent !== window) {
        return new URLSearchParams(window.parent.location.search).get("lang");
      }
    } catch {
      return null;
    }
    return null;
  }

  function normalizeLang(value) {
    if (!value) return null;
    var lang = String(value).toLowerCase();
    if (lang === "cn" || lang === "zh-cn" || lang === "zh-hans") return "zh";
    if (lang.indexOf("en") === 0) return "en";
    if (lang.indexOf("es") === 0) return "es";
    if (SUPPORTED.indexOf(lang) >= 0) return lang;
    return null;
  }

  function initialLang() {
    var own = new URLSearchParams(window.location.search).get("lang");
    var stored = window.localStorage && (window.localStorage.getItem("axis:site-language") || window.localStorage.getItem("pbo-lang"));
    var htmlLang = document.documentElement.lang;
    return normalizeLang(own) || normalizeLang(getParentLang()) || normalizeLang(stored) || normalizeLang(htmlLang) || "en";
  }

  function storeOriginal(node, key) {
    if (!node.__pboOriginal) node.__pboOriginal = {};
    if (node.__pboOriginal[key] === undefined) node.__pboOriginal[key] = node[key];
    return node.__pboOriginal[key];
  }

  function translateValue(value, lang) {
    if (SUPPORTED.indexOf(lang) < 0) lang = "en";
    var dict = TEXT[lang] || {};
    var compact = String(value).replace(/\s+/g, " ").trim();
    if (!compact) return value;
    var normalized = compact.replace(/\s+([,.])/g, "$1");
    var upper = normalized.toUpperCase();
    if (upper === "EXPERIENCIAS INESPERADAS EN LUGARES INUSUALES") return "UNEXPECTED EXPERIENCES IN UNUSUAL PLACES";
    if (upper === "EXPERIENCIAS INESPERADAS EN LUGARES INUSUALES.") return "UNEXPECTED EXPERIENCES IN UNUSUAL PLACES.";
    return dict[value] || dict[compact] || dict[normalized] || value;
  }

  function translateTextNodes(lang) {
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var parent = node.parentElement;
        if (!parent) return NodeFilter.FILTER_REJECT;
        if (/^(SCRIPT|STYLE|NOSCRIPT|TEXTAREA)$/.test(parent.tagName)) return NodeFilter.FILTER_REJECT;
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (node) {
      var original = storeOriginal(node, "nodeValue");
      node.nodeValue = translateValue(original, lang);
    });
  }

  function translateAttributes(lang) {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
    document.title = translateValue(storeOriginal(document, "title"), lang);
    document.querySelectorAll("[title],[alt],[aria-label],[data-label],[data-ph]").forEach(function (el) {
      ["title", "alt", "aria-label", "data-label", "data-ph"].forEach(function (attr) {
        if (!el.hasAttribute(attr)) return;
        var key = "attr:" + attr;
        if (!el.__pboOriginal) el.__pboOriginal = {};
        if (el.__pboOriginal[key] === undefined) el.__pboOriginal[key] = el.getAttribute(attr);
        el.setAttribute(attr, translateValue(el.__pboOriginal[key], lang));
      });
    });
  }

